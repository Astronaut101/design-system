import {
  ArrowUp,
  Blend,
  BookOpen,
  ChartColumn,
  CircleCheck,
  CircleDashed,
  CircleX,
  Contrast,
  Copy,
  Ellipsis,
  File,
  House,
  Info,
  Monitor,
  Moon,
  Palette,
  Pipette,
  Plus,
  Ruler,
  Save,
  Search,
  Settings,
  Shapes,
  Sparkles,
  Sun,
  ToggleRight,
  Trash,
  TriangleExclamationPoint,
  User,
  createElement,
  type IconNode,
} from 'lucide';

// Named imports, so the bundle holds only these rather than all of Lucide.
export const ICON_NODES: Record<string, IconNode> = {
  'arrow-up': ArrowUp,
  blend: Blend,
  'book-open': BookOpen,
  'chart-column': ChartColumn,
  'circle-check': CircleCheck,
  'circle-dashed': CircleDashed,
  'circle-x': CircleX,
  contrast: Contrast,
  copy: Copy,
  ellipsis: Ellipsis,
  file: File,
  house: House,
  info: Info,
  monitor: Monitor,
  moon: Moon,
  palette: Palette,
  pipette: Pipette,
  plus: Plus,
  ruler: Ruler,
  save: Save,
  search: Search,
  settings: Settings,
  shapes: Shapes,
  sparkles: Sparkles,
  sun: Sun,
  'toggle-right': ToggleRight,
  trash: Trash,
  'triangle-exclamation-point': TriangleExclamationPoint,
  user: User,
};

export const lucideSvg = (name: string) => {
  const node = ICON_NODES[name];
  if (!node) throw new Error(`Import the Lucide icon "${name}" in site/icons.ts`);
  return createElement(node, { class: 'ic', 'aria-hidden': 'true' }).outerHTML;
};
