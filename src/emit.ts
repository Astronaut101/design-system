import { hexToRgb } from './color-math.ts';
import type { Mode } from './chart-gates.ts';
import type { Model, Role, RoleValue } from './tokens.ts';

const HEADER = '/* Generated by scripts/build.ts from src/spec.ts. Do not edit by hand. */\n';

const SCHEME_RULES = `:root { color-scheme: light dark; }
[data-theme="light"] { color-scheme: light; color: var(--fg-default); }
[data-theme="dark"] { color-scheme: dark; color: var(--fg-default); }
`;

const rampDecls = (m: Model) =>
  Object.entries(m.ramps).flatMap(([ramp, stops]) =>
    Object.entries(stops).map(([tone, hex]) => `--ramp-${ramp}-${tone}: ${hex};`),
  );

const roleValue = (v: RoleValue) => (v.alpha === undefined ? `var(--ramp-${v.ramp}-${v.tone})` : v.css);

const roleDecls = (m: Model, family: Role['family']) =>
  m.roles
    .filter((r) => r.family === family)
    .map((r) => `--${r.name}: light-dark(${roleValue(r.light)}, ${roleValue(r.dark)});`);

const pairs = (prefix: string, light: string[], dark: string[]) =>
  light.map((hex, i) => `--${prefix}-${i + 1}: light-dark(${hex}, ${dark[i]});`);

const chartDecls = (m: Model) => {
  const { categorical: c, sequential: s, diverging: d, grid, axis } = m.chart;
  return [
    ...pairs('chart', c.light, c.dark),
    ...pairs('chart-seq', s.light, s.dark),
    ...pairs('chart-div', d.light, d.dark),
    `--chart-grid: light-dark(${grid.light.hex}, ${grid.dark.hex});`,
    `--chart-axis: light-dark(${axis.light.hex}, ${axis.dark.hex});`,
  ];
};

const elevationDecls = (m: Model) => Object.entries(m.elevation).map(([name, value]) => `--shadow-${name}: ${value};`);

const rampSection = (m: Model): [string, string[]] => [
  'Internal tonal ramps. The number is the HCT tone. Apps should use the tokens below.',
  rampDecls(m),
];

// Firefox and WebKit resolve light-dark() where a custom property is declared, not where it's used.
// Declaring these on every data-theme element is what lets part of a page force a mode there.
const MODE_SCOPE = ':root, [data-theme]';

const modeSections = (m: Model): [string, string[]][] => [
  ['Text and icons.', roleDecls(m, 'fg')],
  ['Backgrounds.', roleDecls(m, 'bg')],
  ['Borders.', roleDecls(m, 'border')],
  ['Focus ring.', roleDecls(m, 'focus')],
  ['Chart palettes.', chartDecls(m)],
  ['Mode-aware shadows.', elevationDecls(m)],
];

const block = (selector: string, sections: [string, string[]][], indent = '') =>
  `${indent}${selector} {\n${sections
    .map(([title, lines]) => `${indent}  /* ${title} */\n${lines.map((l) => `${indent}  ${l}`).join('\n')}`)
    .join('\n\n')}\n${indent}}\n`;

export const emitTokensCss = (m: Model) =>
  HEADER +
  SCHEME_RULES +
  '\n' +
  block(':root', [
    rampSection(m),
    ['Sizing: Tailwind v4 defaults, unchanged.', m.sizing.map((t) => `${t.name}: ${t.value};`)],
    ['Spacing steps for apps without Tailwind.', m.spaceSteps.map((s) => `--space-${String(s).replace('.', '-')}: calc(var(--spacing) * ${s});`)],
  ]) +
  '\n' +
  block(MODE_SCOPE, modeSections(m));

// fg-* becomes text-*, bg-* stays bg-*, and border-* stays border-*. Each family exists only in
// its own Tailwind namespace, so utilities such as text-accent-emphasis are never generated.
const NAMESPACE: Partial<Record<Role['family'], string[]>> = {
  fg: ['--text-color'],
  bg: ['--background-color'],
  border: ['--border-color'],
  focus: ['--ring-color', '--outline-color'],
};

const themeDecls = (m: Model) =>
  m.roles.flatMap((r) => {
    const name = r.family === 'focus' ? 'focus' : r.name.slice(r.family.length + 1);
    return (NAMESPACE[r.family] ?? []).map((ns) => `${ns}-${name}: var(--${r.name});`);
  });

const chartThemeDecls = (m: Model) => {
  const count = (prefix: string, n: number) =>
    Array.from({ length: n }, (_, i) => `--color-${prefix}-${i + 1}: var(--${prefix}-${i + 1});`);
  return [
    ...count('chart', m.chart.categorical.light.length),
    ...count('chart-seq', m.chart.sequential.light.length),
    ...count('chart-div', m.chart.diverging.light.length),
    '--color-chart-grid: var(--chart-grid);',
    '--color-chart-axis: var(--chart-axis);',
  ];
};

export const emitTailwindCss = (m: Model) =>
  HEADER +
  `/* Import after tailwindcss. Sizing stays on Tailwind's defaults. The stock color palette is
   removed, so every color in utilities comes from the system. */
@layer theme {
${block(':root', [rampSection(m)], '  ')}
${block(MODE_SCOPE, modeSections(m), '  ')}}

@theme inline {
  --color-*: initial;
  --color-white: #ffffff;
  --color-black: #000000;

${[...themeDecls(m), ...chartThemeDecls(m)].map((l) => `  ${l}`).join('\n')}
}

@theme {
${elevationDecls(m).map((l) => `  ${l}`).join('\n')}
}

@custom-variant dark {
  @media (prefers-color-scheme: dark) {
    &:where(:root:not([data-theme="light"]), :root:not([data-theme="light"]) *) {
      @slot;
    }
  }
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
}

@layer base {
  ${SCHEME_RULES.trim().replace(/\n/g, '\n  ')}
}
`;

const dtcgColor = (hex: string, extra?: object, alpha?: number) => ({
  $type: 'color',
  $value: {
    colorSpace: 'srgb',
    components: hexToRgb(hex).map((c) => Number(c.toFixed(4))),
    ...(alpha === undefined ? {} : { alpha }),
    hex,
  },
  ...(extra ? { $extensions: { 'as.oestergaard.hct': extra } } : {}),
});

const dtcgDimension = (value: string) => {
  const match = value.match(/^(-?[\d.]+)(rem|px)$/);
  return match
    ? { $type: 'dimension', $value: { value: Number(match[1]), unit: match[2] } }
    : { $value: value };
};

export const emitDtcg = (m: Model, mode: Mode) => {
  const family = (f: Role['family']) =>
    Object.fromEntries(
      m.roles
        .filter((r) => r.family === f)
        .map((r) => [
          r.name.slice(f.length + 1) || r.name,
          {
            ...dtcgColor(r[mode].hex, { ramp: r[mode].ramp, tone: r[mode].tone }, r[mode].alpha),
            $description: r.note,
          },
        ]),
    );
  const series = (xs: string[]) => Object.fromEntries(xs.map((hex, i) => [String(i + 1), dtcgColor(hex)]));
  const size: Record<string, Record<string, object>> = {};
  for (const t of m.sizing) {
    if (!/^--(spacing$|radius-|breakpoint-|container-|text-[^-]+$)/.test(t.name)) continue;
    (size[t.group] ??= {})[t.name.replace(/^--/, '')] = dtcgDimension(t.value);
  }
  return {
    $description: `Oestergaard-AS design tokens, ${mode} mode. Generated, do not edit.`,
    color: {
      fg: family('fg'),
      bg: family('bg'),
      border: family('border'),
      focus: family('focus').focus,
      chart: {
        categorical: series(m.chart.categorical[mode]),
        sequential: series(m.chart.sequential[mode]),
        diverging: series(m.chart.diverging[mode]),
        grid: dtcgColor(m.chart.grid[mode].hex),
        axis: dtcgColor(m.chart.axis[mode].hex),
      },
    },
    size,
  };
};

const flatRoles = (m: Model, mode: Mode) =>
  Object.fromEntries(m.roles.map((r) => [r.name, r[mode].css]));

// For canvas-based chart libraries and native code that cannot read CSS variables.
export const emitJs = (m: Model) => {
  const data = {
    light: { color: flatRoles(m, 'light') },
    dark: { color: flatRoles(m, 'dark') },
    chart: {
      categorical: m.chart.categorical,
      sequential: m.chart.sequential,
      diverging: m.chart.diverging,
      grid: { light: m.chart.grid.light.hex, dark: m.chart.grid.dark.hex },
      axis: { light: m.chart.axis.light.hex, dark: m.chart.axis.dark.hex },
    },
    iconSizes: m.iconSizes,
  };
  return (
    '// Generated by scripts/build.ts. Do not edit by hand.\n' +
    Object.entries(data)
      .map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};`)
      .join('\n') +
    '\n'
  );
};

export const emitDts = (m: Model) => {
  const roles = m.roles.map((r) => `'${r.name}'`).join(' | ');
  return `// Generated by scripts/build.ts. Do not edit by hand.
export type ColorRole = ${roles};
export type Mode = 'light' | 'dark';
type ByMode<T> = Record<Mode, T>;
export declare const light: { color: Record<ColorRole, string> };
export declare const dark: { color: Record<ColorRole, string> };
export declare const chart: {
  categorical: ByMode<string[]>;
  sequential: ByMode<string[]>;
  diverging: ByMode<string[]>;
  grid: ByMode<string>;
  axis: ByMode<string>;
};
export declare const iconSizes: ${JSON.stringify(m.iconSizes)};
`;
};
